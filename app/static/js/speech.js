/**
 * static/js/speech.js — Speech-to-Text & Text-to-Speech (Browser-Side)
 * ======================================================================
 * Why this file exists:
 *   Handles browser-side speech functionality:
 *
 *   SPEECH-TO-TEXT (STT):
 *   - Uses the Web Speech API (window.SpeechRecognition) for real-time
 *     browser-based transcription (no server round-trip needed).
 *   - Falls back to recording audio and uploading to /api/speech-to-text
 *     for server-side transcription if Web Speech API is unavailable.
 *
 *   TEXT-TO-SPEECH (TTS):
 *   - Plays audio files generated by the server (/api/text-to-speech).
 *   - The server uses gTTS; this file just handles playback.
 */

'use strict';

document.addEventListener('DOMContentLoaded', () => {
    const btnMic = document.getElementById('btn-mic');
    if (!btnMic) return;

    let isRecording = false;

    // ── Check for Web Speech API ────────────────────────
    const SpeechRecognition =
        window.SpeechRecognition || window.webkitSpeechRecognition;

    if (SpeechRecognition) {
        initWebSpeechAPI(btnMic, SpeechRecognition);
    } else {
        initFallbackRecording(btnMic);
    }
});


/**
 * Strategy 1: Web Speech API (Chrome, Edge, Safari)
 * Real-time transcription in the browser — no upload needed.
 */
function initWebSpeechAPI(btnMic, SpeechRecognition) {
    const recognition = new SpeechRecognition();
    recognition.lang = 'en-US';
    recognition.interimResults = false;
    recognition.continuous = false;

    let isRecording = false;

    btnMic.addEventListener('click', () => {
        if (isRecording) {
            recognition.stop();
            btnMic.classList.remove('recording');
            isRecording = false;
        } else {
            recognition.start();
            btnMic.classList.add('recording');
            isRecording = true;
        }
    });

    recognition.addEventListener('result', (event) => {
        const transcript = event.results[0][0].transcript;
        console.log('STT Result:', transcript);

        // Send transcribed text to chat
        if (window.sendChatMessage) {
            window.sendChatMessage(transcript);
        }
    });

    recognition.addEventListener('end', () => {
        btnMic.classList.remove('recording');
        isRecording = false;
    });

    recognition.addEventListener('error', (event) => {
        console.error('STT Error:', event.error);
        btnMic.classList.remove('recording');
        isRecording = false;
    });
}


/**
 * Strategy 2: Fallback — Record audio blob and upload to server.
 * Used when Web Speech API is not available.
 */
function initFallbackRecording(btnMic) {
    let mediaRecorder = null;
    let audioChunks = [];
    let isRecording = false;

    btnMic.addEventListener('click', async () => {
        if (isRecording && mediaRecorder) {
            mediaRecorder.stop();
            btnMic.classList.remove('recording');
            isRecording = false;
            return;
        }

        try {
            const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
            mediaRecorder = new MediaRecorder(stream);
            audioChunks = [];

            mediaRecorder.addEventListener('dataavailable', (e) => {
                audioChunks.push(e.data);
            });

            mediaRecorder.addEventListener('stop', async () => {
                const audioBlob = new Blob(audioChunks, { type: 'audio/wav' });
                stream.getTracks().forEach((t) => t.stop());

                // Upload to server for transcription
                const formData = new FormData();
                formData.append('audio', audioBlob, 'recording.wav');

                try {
                    const response = await fetch('/api/speech-to-text', {
                        method: 'POST',
                        body: formData,
                    });
                    const data = await response.json();

                    if (data.text && window.sendChatMessage) {
                        window.sendChatMessage(data.text);
                    }
                } catch (error) {
                    console.error('Upload error:', error);
                }
            });

            mediaRecorder.start();
            btnMic.classList.add('recording');
            isRecording = true;

        } catch (error) {
            console.error('Microphone access denied:', error);
            alert('Please allow microphone access to use voice input.');
        }
    });
}
